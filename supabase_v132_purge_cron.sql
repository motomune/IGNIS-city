-- v132: アカウント削除の自動実行（毎日）
--
-- v128 で purge_deleted_accounts() を作ったが、これを呼ぶものが無かった。
-- そのままだと利用規約・プライバシーポリシーに「申請から30日後に削除します」と
-- 書いてあるのに、実際には誰も削除を実行しない＝守れない約束になっていた。
--
-- 毎日 JST 13:30（UTC 4:30）に実行する。30日を過ぎた予約だけが対象で、
-- 予約が無ければ何もしない。
--
-- 適用済み（2026-08-15 に管理APIで実行）。

select cron.schedule(
  'purge-deleted-accounts',
  '30 4 * * *',
  $$ select public.purge_deleted_accounts(); $$
);
